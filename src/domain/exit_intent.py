"""用户控制流意图的确定性检测（纯规则，零 I/O、零框架依赖）。

三类判定，均用纯规则——它们都发生在「用户这句话算不算某个动作」的边界上，
必须机器可复现（契合 PROMPT_DESIGN「确定性信息由代码判定」）：

- ``is_exit_intent``：用户说「停 / 结束 / 今天就到这」→ 结束会话。为避免把
  「我还没结束学习」这类反向表达误判为退出，只对**短文本**（≤8 字符）命中判定。
- ``is_advance_directive``：用户**明确指令**直接推进学习（「直接进入下一阶段 /
  直接推进 / 不用再问」）→ 里程碑勾选后免确认。关键词都带「直接」或豁免类词，
  指令性强，放宽到 ≤30 字符命中即判；误判代价低（少问/多问一次）。
- ``is_completion_claim``：用户声明自己已完成/已掌握 → 里程碑免验收直接勾选。

前两者是**控制流**：判错会改变流程走向（该结束的没结束、该问的没问），所以词表
宁可窄、必须确定。第三个不同，它是**快路径**：判错只是多跑或少跑一次 LLM 验收，
「这句话算不算完成声明」本质是语义判断，最终归验收员——故它的词表偏保守，
未命中不代表没完成（见该函数 docstring）。
"""

import re

_EXIT_RE = re.compile(
    r"(结束|退出|停止|停|不学了|今天就到|就到这里|算了吧|先这样吧|太乱了|收工|不搞了|放弃)",
    re.IGNORECASE,
)
_MAX_LEN = 8
# 语气词/标点：退出短语的允许残留（"结束了" → 残留"了" → 仍判退出）
_PARTICLES = "吧了啊呢嘛好呀哦这~～。，,.！!？?"


def is_exit_intent(text: str) -> bool:
    """用户输入是否表达退出意图。

    判定规则（防误判「我还没结束学习呢」这类反向短句）：
    1. 短文本（≤8 字符）命中退出关键词；
    2. 且关键词外的残留只含语气词/标点——即整句基本就是"结束/不学了"的意思。
    """
    t = (text or "").strip()
    if not t or len(t) > _MAX_LEN:
        return False
    m = _EXIT_RE.search(t)
    if not m:
        return False
    residue = (t[: m.start()] + t[m.end():]).strip(_PARTICLES)
    return not residue


# 明确推进/豁免指令关键词：带「直接」前缀的推进短语，或「不用/别问」类豁免词。
# 命中即判定（不做严格残留检查——「不用再确认了，直接进入下一阶段」这类复合句
# 残留非语气词，但仍是明确指令）；只限短文本防长句里的普通内容误判。
_ADVANCE_RE = re.compile(
    r"(直接(进入|开始|推进|进行|做|学|上)?(下一|下一阶段|下个阶段|下一步|下阶段|下一里程碑|下一个里程碑|后续|后面)"
    r"|直接(推进|继续|开始|进行)"
    r"|(不用|无需|别)(再)?(问|确认|问了|确认了|问我|确认我|过问))",
    re.IGNORECASE,
)
_ADV_MAX_LEN = 30


def is_advance_directive(text: str) -> bool:
    """用户上一条回复是否为「直接推进 / 免确认」的明确指令。

    命中（如「直接进入下一阶段」「直接推进」「不用再问」）→ True：里程碑勾选后
    免去确认询问直接推进。未命中（如「进入下一阶段之前先把当前讲完」）→ False。
    """
    t = (text or "").strip()
    if not t or len(t) > _ADV_MAX_LEN:
        return False
    return bool(_ADVANCE_RE.search(t))


# 用户完成声明关键词：里程碑常在对话外完成——动作型在 IDE 里（「本地跑通 hello world」），
# 认知型在脑子里（「能说清 XX」）——对话中天然无证据。用户明确声明完成 → 验收豁免
# （信任用户对自己离线动作的判断）。故词表覆盖四类措辞：动作完成、自评已掌握、
# 认知类自述（我知道 / 我懂了 / 我明白了）、免答/跳过。
#
# 定位是**快路径**而非闸门：命中省掉一次 LLM 验收调用，未命中**不等于没完成**，
# 照常送验收员按语义判。故此处宁可漏判、不可错判——漏判只多花一次调用，错判会把
# 没做完的里程碑放行。也是因此，认知类只收第一人称或完成态说法（「我知道」「我懂了」
# 「知道了」），不收光秃秃的「知道/懂/明白」——那会命中「我想知道为什么」这类提问。
_CLAIM_RE = re.compile(
    r"(学会了|都会了|我会了|掌握了|搞定了|做完了|完成了|跑通了|装好了|弄好了"
    r"|过了一遍|脑子里过|不一一回答|不用逐条|不用答了|不必回答"
    r"|我知道|我懂了|我明白了|我清楚了|我了解了|我理解了"
    r"|知道了|懂了|搞清楚了|搞明白了|弄懂了"
    r"|直接勾|勾了吧|勾选吧|跳过吧)",
    re.IGNORECASE,
)
# 免答/自评类表达天然出现在长句里（「我脑子里过了一遍，就不一一回答你了，直接下一步」），
# 40 字符会把这类长句挡在门外。
_CLAIM_MAX_LEN = 60
# 否定/疑问守卫：「还没搞定」「搞定了没？」含关键词但不是完成声明。
# 认知类额外补上完整否定式（不知道/不懂/不清楚…）：「我知道」这类第一人称说法本身
# 不会被「我不 X」命中（「我不知道」不含子串「我知道」），但完成态说法会被命中
# （「我不明白了」含「明白了」），故显式列出，避免否定式被误判成豁免。
_CLAIM_NEGATE_RE = re.compile(
    r"(还没|尚未|没有|没|别|先别|吗|么"
    r"|不知道|不懂|不清楚|不了解|不理解|不明白)")


def is_completion_claim(text: str) -> bool:
    """用户上一条回复是否**明确**声明「已完成 / 直接勾选」（里程碑验收豁免）。

    命中且不含否定/疑问词（「还没搞定」「搞定了没？」不误判）→ True：跳过验收
    直接勾选。误豁免代价 = 少验一次（用户本就是完成与否的最终权威）。

    这是**快路径**，不是闸门：返回 False **不等于**用户没完成，只是没命中词表——
    调用方照常送验收员按语义判。故本函数偏保守（宁可漏判，多花一次 LLM 调用，
    也不要把没做完的里程碑放行）；「这个我知道」「我懂了」这类措辞不在表内的
    同义表达，由验收员兜住，不靠扩表。

    边界：只说「往下走」（「直接下一步」）**不算**声明完成——那是推进授权，由
    ``is_advance_directive`` 管；该里程碑能否勾选，交给验收员按对话证据判。
    """
    t = (text or "").strip()
    if not t or len(t) > _CLAIM_MAX_LEN:
        return False
    if not _CLAIM_RE.search(t):
        return False
    return not _CLAIM_NEGATE_RE.search(t)
